/** Pinned Code-pack sources. Versions are tags or commit SHAs that the build fetches. */

export type CleanKind = 'md' | 'rst' | 'html' | 'java' | 'go' | 'rust' | 'texi' | 'adoc'

export interface RawFile {
  path: string
  library: string
  clean: CleanKind
}

export interface TreeSpec {
  repo: string
  /** Tag or full commit SHA. */
  ref: string
  dir: string
  clean: CleanKind
  /** Basename or path must match. */
  match: string
  limit: number
  libraryFrom?: 'stem' | 'fixed'
  library?: string
}

export interface SourceSpec {
  id: string
  title: string
  version: string
  licence: string
  url: string
  attribution: string
  language: string
  library: string
  maxChars: number
  rawBase?: string
  files?: RawFile[]
  tree?: TreeSpec
  archiveUrl?: string
  archivePick?: string[]
  archiveClean?: CleanKind
  licenceUrl?: string
  licenceIncludes?: string
}

